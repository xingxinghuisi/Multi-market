const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const base=process.env.RADAR_TEST_BASE_URL;
  const output=path.resolve(__dirname,'../../test-results/smart-money');fs.mkdirSync(output,{recursive:true});
  try {
    for(const width of [390,1280]) {
      const context=await browser.newContext({viewport:{width,height:900},serviceWorkers:'block',reducedMotion:'reduce',colorScheme:width===1280?'dark':'light'});
      const page=await context.newPage(), errors=[];
      await page.request.post(base+'/__fixture__/smart-money-price?price=16');
      page.on('pageerror',error=>errors.push(error.message));
      await page.goto(base+'/#register');
      await page.getByLabel('用户名',{exact:true}).fill('smart_'+width+'_'+Date.now());
      await page.getByLabel('密码',{exact:true}).fill('SyntheticBrowser2026');
      await page.getByRole('button',{name:'注册并进入',exact:true}).click();
      await page.getByRole('heading',{name:'市场，尽在掌握'}).waitFor();
      const before=(await(await page.request.get(base+'/__fixture__/smart-money')).json()).calls;
      await page.goto(base+'/#asset/1');
      const load=page.getByRole('button',{name:'查看聪明钱快照',exact:true});await load.waitFor();
      assert.equal((await(await page.request.get(base+'/__fixture__/smart-money')).json()).calls,before);
      await load.click();
      await page.getByText('源时间口径待核实',{exact:true}).waitFor();
      const card=page.locator('.smart-money-card');
      assert.match(await card.innerText(),/最近成功读取时间/);
      assert.match(await card.innerText(),/盈利巨鲸人数\s+0/);
      assert.match(await card.innerText(),/盈利巨鲸人数\s+未提供/);
      assert.match(await card.innerText(),/不用于实时提醒/);
      assert.equal(await card.locator('[data-smart-pnl="long.whales_usdt"]').innerText(),'+$150');
      assert.equal(await card.locator('[data-smart-pnl="short.whales_usdt"]').innerText(),'+$450');
      assert.match(await card.innerText(),/不含手续费、资金费/);
      const pnlCalls=(await(await page.request.get(base+'/__fixture__/smart-money')).json()).calls;
      await page.getByText('行情已连接',{exact:true}).waitFor();
      await page.request.post(base+'/__fixture__/smart-money-price?price=20');
      await page.waitForFunction(()=>document.querySelector('[data-smart-pnl="long.whales_usdt"]')?.textContent==='+$450');
      assert.equal(await card.locator('[data-smart-pnl="short.whales_usdt"]').innerText(),'-$150');
      assert.equal((await(await page.request.get(base+'/__fixture__/smart-money')).json()).calls,pnlCalls);
      await page.request.post(base+'/__fixture__/smart-money-price?price=14');
      await page.waitForFunction(()=>document.querySelector('[data-smart-pnl="long.whales_usdt"]')?.textContent==='$0');
      await page.request.post(base+'/__fixture__/smart-money-price?price=14&stale=true');
      await card.locator('[data-smart-pnl-meta]').filter({hasText:'成交行情较旧，暂停计算'}).waitFor();
      assert.equal(await card.locator('[data-smart-pnl="long.whales_usdt"]').innerText(),'未提供');
      await page.request.post(base+'/__fixture__/smart-money-price?price=16');
      await page.waitForFunction(()=>document.querySelector('[data-smart-pnl="long.whales_usdt"]')?.textContent==='+$150');
      await card.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'pnl-'+width+'.png')});
      await page.request.post(base+'/__fixture__/smart-money-fail');
      await page.getByRole('button',{name:'刷新快照',exact:true}).click();
      await card.getByRole('alert').waitFor();
      assert.match(await card.innerText(),/当前服务器暂时无法访问/);
      assert.match(await card.innerText(),/总持仓名义价值/);
      assert.equal(await card.locator('[data-smart-pnl="long.whales_usdt"]').innerText(),'未提供');
      await card.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'snapshot-'+width+'.png')});
      await page.getByRole('button',{name:'设置群体变化提醒',exact:true}).click();
      const form=page.locator('[data-smart-money-form]');await form.waitFor();
      assert.equal(await form.getByLabel('开启群体变化提醒',{exact:true}).isChecked(),false);
      const initial=(await(await page.request.get(base+'/api/subscriptions')).json());
      assert.equal(initial.length,1);assert.equal(initial[0].alert_type,'smart_money');assert.equal(initial[0].enabled,false);
      await form.getByLabel('开启群体变化提醒',{exact:true}).check();
      await form.getByLabel('监控巨鲸人数变化',{exact:true}).uncheck();
      await form.getByLabel('监控巨鲸持仓数量变化',{exact:true}).uncheck();
      await form.getByRole('button',{name:'保存聪明钱订阅',exact:true}).click();
      await form.getByText('至少选择巨鲸人数或持仓数量中的一项。',{exact:true}).waitFor();
      await form.getByLabel('监控巨鲸人数变化',{exact:true}).check();
      await form.getByLabel('人数变化门槛（人）',{exact:true}).fill('3');
      await form.getByLabel('提醒间隔（秒）',{exact:true}).fill('900');
      const savedResponse=page.waitForResponse(response=>response.url().endsWith('/api/subscriptions')&&response.request().method()==='PUT');
      await form.getByRole('button',{name:'保存聪明钱订阅',exact:true}).click();
      assert.equal((await savedResponse).status(),200);
      await page.getByText('聪明钱订阅已保存；首次采样仅建立对照。',{exact:true}).waitFor();
      const saved=(await(await page.request.get(base+'/api/subscriptions')).json())[0];
      assert.equal(saved.enabled,true);assert.equal(saved.config.min_whale_count_change,3);
      assert.equal(saved.config.watch_whale_quantity,false);assert.equal(saved.config.cooldown_seconds,900);
      assert.match(await form.innerText(),/等待首次采样/);
      assert.deepEqual(errors,[]);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      await form.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'subscription-'+width+'.png')});
      await context.close();
      console.log('PASS '+width+'px: opt-in snapshot, disabled-by-default subscription, metric validation, independent saved thresholds and responsive theme');
    }
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
